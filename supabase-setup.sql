CREATE FUNCTION public.update_profile(p_username text, p_x_username text, p_wallet_address text)
RETURNS json LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_user uuid := auth.uid(); v_profile public.profiles;
  v_username text; v_x text; v_wallet text;
  v_x_bonus integer := 0; v_wallet_bonus integer := 0;
BEGIN
  IF v_user IS NULL THEN
    RETURN json_build_object('ok', false, 'error', 'NOT_AUTHENTICATED');
  END IF;
  v_profile := public.ensure_profile();

  v_username := NULLIF(btrim(COALESCE(p_username, '')), '');
  v_x := NULLIF(btrim(regexp_replace(COALESCE(p_x_username, ''), '^@+', '')), '');
  v_wallet := NULLIF(btrim(COALESCE(p_wallet_address, '')), '');

  IF v_username IS NOT NULL AND v_username !~ '^[A-Za-z0-9_]{3,20}$' THEN
    RETURN json_build_object('ok', false, 'error', 'INVALID_USERNAME');
  END IF;
  IF v_username IS NOT NULL AND EXISTS (
       SELECT 1 FROM public.profiles p
        WHERE lower(p.username) = lower(v_username) AND p.id <> v_user) THEN
    RETURN json_build_object('ok', false, 'error', 'USERNAME_TAKEN');
  END IF;
  IF v_x IS NOT NULL AND v_x !~ '^[A-Za-z0-9_]{1,15}$' THEN
    RETURN json_build_object('ok', false, 'error', 'INVALID_X');
  END IF;
  IF v_wallet IS NOT NULL AND NOT public.is_valid_solana_address(v_wallet) THEN
    RETURN json_build_object('ok', false, 'error', 'INVALID_WALLET');
  END IF;

  IF v_x IS NOT NULL AND NOT COALESCE(v_profile.x_bonus_claimed, false) THEN
    v_x_bonus := 5;
  END IF;
  IF v_wallet IS NOT NULL AND NOT COALESCE(v_profile.wallet_bonus_claimed, false) THEN
    v_wallet_bonus := 5;
  END IF;

  UPDATE public.profiles
     SET username = v_username, x_username = v_x, wallet_address = v_wallet,
         x_bonus_claimed = x_bonus_claimed OR (v_x IS NOT NULL),
         wallet_bonus_claimed = wallet_bonus_claimed OR (v_wallet IS NOT NULL),
         wp = COALESCE(wp, 0) + v_x_bonus + v_wallet_bonus
   WHERE id = v_user
  RETURNING * INTO v_profile;

  RETURN json_build_object('ok', true, 'username', v_profile.username,
    'x_username', v_profile.x_username, 'wallet_address', v_profile.wallet_address,
    'x_bonus', v_x_bonus, 'wallet_bonus', v_wallet_bonus,
    'total_bonus', v_x_bonus + v_wallet_bonus);
END $$;

