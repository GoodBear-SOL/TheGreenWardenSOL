CREATE FUNCTION public.get_my_status()
RETURNS json LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_user uuid := auth.uid(); v_profile public.profiles; v_claimed boolean; v_rank integer;
BEGIN
  IF v_user IS NULL THEN
    RETURN json_build_object('ok', false, 'error', 'NOT_AUTHENTICATED');
  END IF;
  v_profile := public.ensure_profile();

  SELECT EXISTS (SELECT 1 FROM public.checkins c
                 WHERE c.user_id = v_user AND c.day = public.manila_today()) INTO v_claimed;
  SELECT 1 + COUNT(*) INTO v_rank FROM public.profiles p WHERE p.wp > v_profile.wp;

  RETURN json_build_object(
    'ok', true, 'id', v_profile.id,
    'google_name', v_profile.google_name, 'avatar_url', v_profile.avatar_url,
    'username', v_profile.username, 'x_username', v_profile.x_username,
    'wallet_address', v_profile.wallet_address, 'wp', v_profile.wp,
    'streak', public.effective_streak(v_profile.last_checkin, v_profile.streak),
    'best_streak', v_profile.best_streak, 'last_checkin', v_profile.last_checkin,
    'claimed_today', v_claimed, 'rank', v_rank,
    'seconds_to_reset', public.manila_seconds_to_reset(),
    'is_admin', COALESCE(v_profile.is_admin, false));
END $$;

CREATE FUNCTION public.claim_checkin()
RETURNS json LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_user uuid := auth.uid(); v_profile public.profiles; v_today date;
  v_streak integer; v_day integer; v_reward integer; v_rows integer;
BEGIN
  IF v_user IS NULL THEN
    RETURN json_build_object('ok', false, 'error', 'NOT_AUTHENTICATED');
  END IF;
  PERFORM public.ensure_profile();
  SELECT * INTO v_profile FROM public.profiles WHERE id = v_user FOR UPDATE;

  v_today := public.manila_today();
  v_streak := CASE WHEN v_profile.last_checkin = v_today - 1
                   THEN COALESCE(v_profile.streak,0) + 1 ELSE 1 END;
  v_day := ((v_streak - 1) % 7) + 1;
  v_reward := public.wp_for_day(v_day);

  INSERT INTO public.checkins (user_id, day, day_in_cycle, wp_awarded)
  VALUES (v_user, v_today, v_day, v_reward)
  ON CONFLICT (user_id, day) DO NOTHING;
  GET DIAGNOSTICS v_rows = ROW_COUNT;

  IF v_rows = 0 THEN
    RETURN json_build_object('ok', false, 'error', 'ALREADY_CLAIMED', 'claimed_today', true);
  END IF;

  UPDATE public.profiles
     SET wp = COALESCE(wp,0) + v_reward, streak = v_streak,
         best_streak = GREATEST(COALESCE(best_streak,0), v_streak),
         last_checkin = v_today
   WHERE id = v_user;

  /* If this Warden was referred, check whether the +300 7-day milestone is now due. */
  PERFORM public._qualify_referral_internal(v_user);

  RETURN json_build_object('ok', true, 'wp_awarded', v_reward, 'day', v_day, 'streak', v_streak);
END $$;

