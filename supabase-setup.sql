/* ---------------- HELPERS ---------------- */

CREATE OR REPLACE FUNCTION public.manila_today()
RETURNS date LANGUAGE sql STABLE AS $$
  SELECT (now() AT TIME ZONE 'Asia/Manila')::date;
$$;

CREATE OR REPLACE FUNCTION public.manila_seconds_to_reset()
RETURNS integer LANGUAGE sql STABLE AS $$
  SELECT GREATEST(0, EXTRACT(EPOCH FROM (
    ((public.manila_today() + 1)::timestamp AT TIME ZONE 'Asia/Manila') - now()
  ))::integer);
$$;

DROP FUNCTION IF EXISTS public.effective_streak(date,integer);
CREATE FUNCTION public.effective_streak(p_last date, p_streak integer)
RETURNS integer LANGUAGE sql STABLE AS $$
  SELECT CASE
    WHEN p_last IS NULL THEN 0
    WHEN p_last >= public.manila_today() - 1 THEN COALESCE(p_streak,0)
    ELSE 0 END;
$$;

CREATE OR REPLACE FUNCTION public.wp_for_day(p_day integer)
RETURNS integer LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE p_day WHEN 1 THEN 5 WHEN 2 THEN 10 WHEN 3 THEN 15 WHEN 4 THEN 20
                    WHEN 5 THEN 25 WHEN 6 THEN 30 WHEN 7 THEN 50 ELSE 5 END;
$$;

CREATE OR REPLACE FUNCTION public.ensure_profile()
RETURNS public.profiles LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_user uuid := auth.uid(); v_profile public.profiles;
BEGIN
  IF v_user IS NULL THEN RAISE EXCEPTION 'NOT_AUTHENTICATED'; END IF;
  INSERT INTO public.profiles (id, google_name, avatar_url)
  SELECT u.id,
         COALESCE(u.raw_user_meta_data->>'full_name', u.raw_user_meta_data->>'name'),
         COALESCE(u.raw_user_meta_data->>'avatar_url', u.raw_user_meta_data->>'picture')
  FROM auth.users u WHERE u.id = v_user
  ON CONFLICT (id) DO NOTHING;
  SELECT * INTO v_profile FROM public.profiles WHERE id = v_user;
  RETURN v_profile;
END $$;

CREATE OR REPLACE FUNCTION public.is_current_user_admin()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT COALESCE((SELECT is_admin FROM public.profiles WHERE id = auth.uid()), false);
$$;

CREATE OR REPLACE FUNCTION public.is_valid_solana_address(p_wallet text)
RETURNS boolean LANGUAGE sql IMMUTABLE AS $$
  SELECT btrim(COALESCE(p_wallet,'')) ~ '^[1-9A-HJ-NP-Za-km-z]{32,44}$';
$$;

/* ---------------- REFERRAL QUALIFICATION (internal, no auth check) ---------------- */

CREATE FUNCTION public._qualify_referral_internal(p_referred uuid)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_ref public.referrals; v_streak integer;
  v_reward integer := 300; v_id bigint;
BEGIN
  SELECT * INTO v_ref
    FROM public.referrals
   WHERE referred_id = p_referred
   FOR UPDATE;

  IF NOT FOUND THEN
    RETURN jsonb_build_object('rewarded', false, 'error', 'REFERRAL_NOT_FOUND');
  END IF;

  /* The +300 milestone can only be awarded once. */
  IF v_ref.active_rewarded_at IS NOT NULL
     OR EXISTS (
          SELECT 1 FROM public.referral_rewards rr
           WHERE rr.referral_id = v_ref.id
             AND rr.reward_type = 'active_referral'
        ) THEN
    RETURN jsonb_build_object(
      'rewarded', false,
      'already_rewarded', true,
      'wp_awarded', 0,
      'streak', 0
    );
  END IF;

  SELECT public.effective_streak(p.last_checkin, p.streak)
    INTO v_streak
    FROM public.profiles p
   WHERE p.id = p_referred;

  /* +300 is earned only when the referred Warden reaches a 7-day streak. */
  IF COALESCE(v_streak, 0) < 7 THEN
    RETURN jsonb_build_object(
      'rewarded', false,
      'qualified', false,
      'streak', COALESCE(v_streak, 0),
      'days_remaining', GREATEST(0, 7 - COALESCE(v_streak, 0))
    );
  END IF;

  INSERT INTO public.referral_rewards
    (referral_id, referrer_id, reward_type, wp_awarded)
  VALUES
    (v_ref.id, v_ref.referrer_id, 'active_referral', v_reward)
  ON CONFLICT (referral_id, reward_type) DO NOTHING
  RETURNING id INTO v_id;

  IF v_id IS NULL THEN
    RETURN jsonb_build_object(
      'rewarded', false,
      'already_rewarded', true,
      'wp_awarded', 0,
      'streak', v_streak
    );
  END IF;

  UPDATE public.referrals
     SET qualified_at = now(),
         active_reward = v_reward,
         active_rewarded_at = now()
   WHERE id = v_ref.id;

  UPDATE public.profiles
     SET wp = COALESCE(wp, 0) + v_reward
   WHERE id = v_ref.referrer_id;

  RETURN jsonb_build_object(
    'rewarded', true,
    'qualified', true,
    'wp_awarded', v_reward,
    'streak', v_streak,
    'referrer_id', v_ref.referrer_id,
    'referred_user', p_referred
  );
END $$;

CREATE FUNCTION public.qualify_referral(p_referred_user uuid)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF auth.uid() IS NULL THEN
    RETURN jsonb_build_object('rewarded', false, 'error', 'NOT_AUTHENTICATED');
  END IF;
  IF p_referred_user <> auth.uid() AND NOT public.is_current_user_admin() THEN
    RETURN jsonb_build_object('rewarded', false, 'error', 'FORBIDDEN');
  END IF;
  RETURN public._qualify_referral_internal(p_referred_user);
END $$;

CREATE FUNCTION public.qualify_my_referral()
RETURNS jsonb LANGUAGE sql SECURITY DEFINER SET search_path = public AS $$
  SELECT public.qualify_referral(auth.uid());
$$;

