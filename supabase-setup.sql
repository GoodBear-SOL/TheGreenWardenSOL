RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF auth.uid() IS NULL THEN RETURN NULL; END IF;
  RETURN public.generate_referral_code();
END $$;

CREATE FUNCTION public.get_my_referral_data()
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_user uuid := auth.uid(); v_code text; v_total integer; v_successful integer;
  v_reward_count integer; v_total_wp integer; v_referred boolean;
  v_streak integer; v_checkins integer; v_qualified boolean;
BEGIN
  IF v_user IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'error', 'NOT_AUTHENTICATED');
  END IF;
  PERFORM public.ensure_profile();
  v_code := public.generate_referral_code();

  SELECT COUNT(*), COUNT(*) FILTER (WHERE qualified_at IS NOT NULL)
    INTO v_total, v_successful FROM public.referrals WHERE referrer_id = v_user;
  SELECT COUNT(*), COALESCE(SUM(wp_awarded), 0)
    INTO v_reward_count, v_total_wp FROM public.referral_rewards WHERE referrer_id = v_user;
  SELECT EXISTS (SELECT 1 FROM public.referrals WHERE referred_id = v_user) INTO v_referred;

  SELECT LEAST(COALESCE(public.effective_streak(p.last_checkin, p.streak), 0), 7)
    INTO v_streak FROM public.profiles p WHERE p.id = v_user;
  SELECT COUNT(*) INTO v_checkins FROM public.checkins WHERE user_id = v_user;

  v_qualified := EXISTS (SELECT 1 FROM public.referrals
                          WHERE referred_id = v_user AND qualified_at IS NOT NULL);

  RETURN jsonb_build_object(
    'ok', true, 'referral_code', v_code,
    'referral_link', 'https://thegreenwarden.xyz/dashboard.html?ref=' || COALESCE(v_code, ''),
    'referral_count', v_total, 'total_referrals', v_total,
    'successful_referrals', v_successful, 'reward_count', v_reward_count,
    'total_wp_earned', v_total_wp, 'has_been_referred', v_referred,
    'activity_streak', COALESCE(v_streak, 0), 'my_activity_streak', COALESCE(v_streak, 0),
    'checkins', v_checkins, 'days_remaining', GREATEST(0, 7 - COALESCE(v_streak, 0)),
    'qualified', v_qualified, 'my_7_day_qualified', v_qualified);
END $$;

CREATE FUNCTION public.attach_referral(p_code text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_user uuid := auth.uid();
  v_code text;
  v_referrer uuid;
  v_referral_id bigint;
  v_reward_id bigint;
  v_initial_reward integer := 200;
BEGIN
  IF v_user IS NULL THEN
    RETURN jsonb_build_object('success', false, 'error', 'NOT_AUTHENTICATED',
                              'message', 'Please sign in first.');
  END IF;
  PERFORM public.ensure_profile();

  v_code := upper(btrim(COALESCE(p_code, '')));
  IF v_code = '' THEN
    RETURN jsonb_build_object('success', false, 'error', 'INVALID_CODE',
                              'message', 'Referral code is required.');
  END IF;

  SELECT user_id INTO v_referrer FROM public.referral_codes
   WHERE upper(referral_code) = v_code LIMIT 1;
  IF v_referrer IS NULL THEN
    RETURN jsonb_build_object('success', false, 'error', 'INVALID_CODE',
                              'message', 'Referral code not found.');
  END IF;
  IF v_referrer = v_user THEN
    RETURN jsonb_build_object('success', false, 'error', 'SELF_REFERRAL',
                              'message', 'You cannot use your own referral code.');
  END IF;
  IF EXISTS (SELECT 1 FROM public.referrals WHERE referred_id = v_user) THEN
    RETURN jsonb_build_object('success', false, 'error', 'ALREADY_REFERRED',
                              'message', 'This account already has a referral attached.');
  END IF;
  IF EXISTS (SELECT 1 FROM public.referrals
              WHERE referrer_id = v_user AND referred_id = v_referrer) THEN
    RETURN jsonb_build_object('success', false, 'error', 'CIRCULAR_REFERRAL',
                              'message', 'This Warden was referred by you.');
  END IF;

  /* Create the referral first. Acceptance itself earns +200 WP. */
  INSERT INTO public.referrals
    (referrer_id, referred_id, referral_code, initial_reward, active_reward)
  VALUES
    (v_referrer, v_user, v_code, 200, 300)
  RETURNING id INTO v_referral_id;

  /* Record the one-time +200 acceptance reward. */
  INSERT INTO public.referral_rewards
    (referral_id, referrer_id, reward_type, wp_awarded)
  VALUES
    (v_referral_id, v_referrer, 'initial_referral', v_initial_reward)
  ON CONFLICT (referral_id, reward_type) DO NOTHING
  RETURNING id INTO v_reward_id;

  IF v_reward_id IS NOT NULL THEN
    UPDATE public.referrals
       SET initial_reward = v_initial_reward,
           initial_rewarded_at = now()
     WHERE id = v_referral_id;

    UPDATE public.profiles
       SET wp = COALESCE(wp, 0) + v_initial_reward
     WHERE id = v_referrer;
  END IF;

  RETURN jsonb_build_object(
    'success', true,
    'message', 'Referral accepted successfully. +200 WP awarded to the referrer.',
    'referrer_id', v_referrer,
    'referral_id', v_referral_id,
    'wp_awarded', CASE WHEN v_reward_id IS NOT NULL THEN v_initial_reward ELSE 0 END
  );
EXCEPTION WHEN unique_violation THEN
  RETURN jsonb_build_object('success', false, 'error', 'ALREADY_REFERRED',
                            'message', 'This account already has a referral attached.');
END $$;

