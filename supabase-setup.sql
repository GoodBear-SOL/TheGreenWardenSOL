CREATE FUNCTION public.generate_referral_code()
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_user uuid := auth.uid(); v_code text; v_try integer := 0;
BEGIN
  IF v_user IS NULL THEN RAISE EXCEPTION 'NOT_AUTHENTICATED'; END IF;
  PERFORM public.ensure_profile();

  SELECT referral_code INTO v_code FROM public.referral_codes WHERE user_id = v_user;
  IF v_code IS NOT NULL THEN RETURN v_code; END IF;

  LOOP
    v_try := v_try + 1;
    v_code := 'GW' || upper(substr(replace(
      CASE WHEN v_try = 1 THEN v_user::text ELSE gen_random_uuid()::text END,
      '-', ''), 1, 8));
    BEGIN
      INSERT INTO public.referral_codes (user_id, referral_code) VALUES (v_user, v_code);
      RETURN v_code;
    EXCEPTION WHEN unique_violation THEN
      SELECT referral_code INTO v_code FROM public.referral_codes WHERE user_id = v_user;
      IF v_code IS NOT NULL THEN RETURN v_code; END IF;
      IF v_try > 10 THEN RAISE; END IF;
    END;
  END LOOP;
END $$;

