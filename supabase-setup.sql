create or replace function public.get_my_referral_data()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare

    v_user uuid := auth.uid();

    v_code text;

    v_total integer := 0;

    v_successful integer := 0;

    v_reward_count integer := 0;

    v_total_wp integer := 0;

    v_referred boolean := false;

    v_qualified boolean := false;

    v_streak integer := 0;

    v_today date;

begin

    if v_user is null then
        raise exception 'AUTH_REQUIRED';
    end if;


    v_code := public.get_my_referral_code();

    v_today := public.manila_today();


    select count(*)
    into v_total
    from public.referrals
    where referrer_id = v_user;


    select count(*)
    into v_successful
    from public.referrals
    where referrer_id = v_user
      and qualified_at is not null;


    select
        count(*),
        coalesce(sum(wp_awarded), 0)
    into
        v_reward_count,
        v_total_wp
    from public.referral_rewards
    where referrer_id = v_user;


    select exists (
        select 1
        from public.referrals
        where referred_id = v_user
    )
    into v_referred;


    /* ------------------------------------------------------------
       Current streak for the referred user
       ------------------------------------------------------------ */

    select coalesce(
        (
            select p.streak
            from public.profiles p
            where p.id = v_user
        ),
        0
    )
    into v_streak;


    select exists (
        select 1
        from public.referrals r
        where r.referred_id = v_user
          and r.qualified_at is not null
    )
    into v_qualified;


    return jsonb_build_object(

        'referral_code',
            v_code,

        'referral_link',
            '?ref=' || v_code,

        /* dashboard fields */
        'total_referrals',
            v_total,

        'total_wp_earned',
            v_total_wp,

        'my_activity_streak',
            least(7, greatest(0, v_streak)),

        'my_7_day_qualified',
            v_qualified,

        /* compatibility fields */
        'referral_count',
            v_total,

        'successful_referrals',
            v_successful,

        'reward_count',
            v_reward_count,

        'activity_streak',
            v_streak,

        'days_remaining',
            greatest(
                0,
                7 - least(7, greatest(0, v_streak))
            ),

        'qualified',
            v_qualified,

        'has_been_referred',
            v_referred

    );

end;
$$;


/* ================================================================
   SECTION 25
   ATTACH REFERRAL
   ================================================================

   IMPORTANT:

   Attaching a referral does NOT award WP.

   The dashboard text currently says "+200" when attachment
   succeeds, but the actual reward rule is:

       successful referral = +200 WP

   Therefore payment is performed by qualify_referral().
   ================================================================ */

create or replace function public.attach_referral(
    p_code text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare

    v_user uuid := auth.uid();

    v_code text :=
        upper(trim(coalesce(p_code, '')));

    v_referrer uuid;

    v_id bigint;

begin

    if v_user is null then

        return jsonb_build_object(
            'ok', false,
            'success', false,
            'message', 'AUTH_REQUIRED'
        );

    end if;


    if v_code = '' then

        return jsonb_build_object(
            'ok', false,
            'success', false,
            'message', 'INVALID_CODE'
        );

    end if;


    select user_id
    into v_referrer
    from public.referral_codes
    where upper(referral_code) = v_code
    limit 1;


    if v_referrer is null then

        return jsonb_build_object(
            'ok', false,
            'success', false,
            'message', 'REFERRAL_CODE_NOT_FOUND'
        );

    end if;


    if v_referrer = v_user then

        return jsonb_build_object(
            'ok', false,
            'success', false,
            'message', 'SELF_REFERRAL'
        );

    end if;


    if exists (
        select 1
        from public.referrals
        where referred_id = v_user
    ) then

        return jsonb_build_object(
            'ok', false,
            'success', false,
            'message', 'ALREADY_REFERRED'
        );

    end if;


    insert into public.referrals (
        referrer_id,
        referred_id,
        referral_code
    )
    values (
        v_referrer,
        v_user,
        v_code
    )
    returning id
    into v_id;


    return jsonb_build_object(

        'ok',
            true,

        'success',
            true,

        'message',
            'REFERRAL_ATTACHED',

        'referral_id',
            v_id,

        'wp_awarded',
            0

    );

end;
$$;


/* ================================================================
   SECTION 26
   QUALIFY REFERRAL
   ================================================================

   Qualification:

   - Referral must exist.
   - Referred Warden must maintain a 7-day consecutive
     activity/check-in streak.
   - Qualification happens only once.
   - Referrer receives EXACTLY +200 WP.
   - referral_rewards receives one successful_referral row.
   - No duplicate reward.
   ================================================================ */

create or replace function public.qualify_referral(
    p_referred_user uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare

    v_referral public.referrals%rowtype;

    v_streak integer := 0;

    v_reward integer := 200;

begin

    if p_referred_user is null then

        return jsonb_build_object(
            'ok', false,
            'rewarded', false,
            'error', 'INVALID_USER'
        );

    end if;


    select *
    into v_referral
    from public.referrals
    where referred_id = p_referred_user
    order by created_at asc
    limit 1
    for update;


    if not found then

        return jsonb_build_object(
            'ok', true,
            'rewarded', false,
            'error', 'NO_REFERRAL'
        );

    end if;


    if v_referral.qualified_at is not null then

        return jsonb_build_object(
            'ok', true,
            'rewarded', false,
            'already_qualified', true,
            'wp_awarded', 0
        );

    end if;


    /* ------------------------------------------------------------
       Read the server-maintained streak.
       claim_checkin() increments this only when the user checks
       in on consecutive Manila dates.
       ------------------------------------------------------------ */

    select coalesce(streak, 0)
    into v_streak
    from public.profiles
    where id = p_referred_user;


    if v_streak < 7 then

        return jsonb_build_object(

            'ok', true,

            'rewarded', false,

            'streak',
                v_streak,

            'required',
                7,

            'wp_awarded',
                0

        );

    end if;


    /* ------------------------------------------------------------
       Mark qualified.
       ------------------------------------------------------------ */

    update public.referrals
    set
        qualified_at = now(),
        active_rewarded_at = now()
    where id = v_referral.id;


    /* ------------------------------------------------------------
       Insert reward only once.
       The unique index prevents duplicate successful rewards.
       ------------------------------------------------------------ */

    insert into public.referral_rewards (
        referral_id,
        referrer_id,
        reward_type,
        wp_awarded
    )
    values (
        v_referral.id,
        v_referral.referrer_id,
        'successful_referral',
        v_reward
    )
    on conflict (
        referral_id,
        reward_type
    )
    do nothing;


    /* ------------------------------------------------------------
       Only increase referrer's WP if the reward row was newly
       inserted.

       This prevents a repeated RPC call from paying +200 again.
       ------------------------------------------------------------ */

    if found then

        update public.profiles
        set wp = coalesce(wp, 0) + v_reward
        where id = v_referral.referrer_id;

    else

        return jsonb_build_object(
            'ok', true,
            'rewarded', false,
            'already_qualified', true,
            'wp_awarded', 0
        );

    end if;


    return jsonb_build_object(

        'ok',
            true,

        'rewarded',
            true,

        'streak',
            v_streak,

        'required',
            7,

        'wp_awarded',
            v_reward,

        'referral_id',
            v_referral.id,

        'referrer_id',
            v_referral.referrer_id

    );

end;
$$;


