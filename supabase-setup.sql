/* ================================================================
   SECTION 11
   TASK BOARD
   ================================================================

   IMPORTANT:
   Dashboard.html supports:

       {
         ok: true,
         tasks: [...],
         task_claims: [...]
       }

   We intentionally return this object form so dashboard.html does
   not enter its legacy array branch that queries nonexistent
   task_claims.id / task_claims.created_at columns.
   ================================================================ */

create or replace function public.get_task_board()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare

    v_user uuid := auth.uid();

    v_tasks jsonb;

    v_claims jsonb;

begin

    if v_user is null then
        return jsonb_build_object(
            'ok', false,
            'error', 'NOT_AUTHENTICATED',
            'tasks', '[]'::jsonb,
            'task_claims', '[]'::jsonb
        );
    end if;


    select coalesce(
        jsonb_agg(
            jsonb_build_object(
                'id', t.id,
                'label', t.label,
                'title', t.label,
                'description', '',
                'platform', 'X',
                'task_type', 'social',
                'url', t.url,
                'task_url', t.url,
                'wp_reward', t.wp_reward,
                'reward_wp', t.wp_reward,
                'needs_proof', t.needs_proof,
                'active', t.active,
                'sort_order', t.sort_order,
                'completed',
                    exists (
                        select 1
                        from public.task_claims tc
                        where tc.user_id = v_user
                          and tc.task_id = t.id
                          and tc.status = 'approved'
                    )
            )
            order by t.sort_order, t.created_at
        ),
        '[]'::jsonb
    )
    into v_tasks
    from public.tasks t
    where t.active = true;


    select coalesce(
        jsonb_agg(
            jsonb_build_object(
                'user_id', tc.user_id,
                'task_id', tc.task_id,
                'proof_url', tc.proof_url,
                'wp_awarded', tc.wp_awarded,
                'status', coalesce(tc.status, 'pending'),
                'claimed_at', tc.claimed_at,
                'reviewed_at', tc.reviewed_at,
                'reviewed_by', tc.reviewed_by
            )
            order by tc.claimed_at desc
        ),
        '[]'::jsonb
    )
    into v_claims
    from public.task_claims tc
    where tc.user_id = v_user;


    return jsonb_build_object(
        'ok', true,
        'tasks', v_tasks,
        'task_claims', v_claims
    );

end;
$$;


/* ================================================================
   SECTION 12
   SUBMIT TASK FOR REVIEW
   ================================================================ */

create or replace function public.submit_task_for_review(
    p_task_id text,
    p_proof_url text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare

    v_user uuid := auth.uid();

    v_task public.tasks;

    v_existing public.task_claims;

    v_url text;

begin

    if v_user is null then
        return jsonb_build_object(
            'ok', false,
            'error', 'NOT_AUTHENTICATED'
        );
    end if;


    if p_task_id is null
       or trim(p_task_id) = '' then

        return jsonb_build_object(
            'ok', false,
            'error', 'INVALID_TASK'
        );

    end if;


    select *
    into v_task
    from public.tasks
    where id = p_task_id
      and active = true;


    if not found then

        return jsonb_build_object(
            'ok', false,
            'error', 'TASK_NOT_FOUND'
        );

    end if;


    if v_task.needs_proof then

        v_url := trim(coalesce(p_proof_url, ''));


        if v_url = '' then

            return jsonb_build_object(
                'ok', false,
                'error', 'PROOF_REQUIRED'
            );

        end if;


        if v_url !~* '^https?://(www\.)?(x\.com|twitter\.com)/.+$' then

            return jsonb_build_object(
                'ok', false,
                'error', 'INVALID_PROOF_URL'
            );

        end if;

    else

        v_url := null;

    end if;


    select *
    into v_existing
    from public.task_claims
    where user_id = v_user
      and task_id = p_task_id;


    if found and v_existing.status = 'approved' then

        return jsonb_build_object(
            'ok', false,
            'error', 'ALREADY_APPROVED'
        );

    end if;


    /* ------------------------------------------------------------
       Existing rejected/pending claim is reused.
       This lets a rejected submission be resubmitted.
       ------------------------------------------------------------ */

    insert into public.task_claims (
        user_id,
        task_id,
        proof_url,
        wp_awarded,
        status,
        claimed_at,
        reviewed_at,
        reviewed_by
    )
    values (
        v_user,
        p_task_id,
        v_url,
        0,
        'pending',
        now(),
        null,
        null
    )
    on conflict (user_id, task_id)
    do update set
        proof_url = excluded.proof_url,
        status = 'pending',
        claimed_at = now(),
        reviewed_at = null,
        reviewed_by = null;


    return jsonb_build_object(
        'ok', true,
        'status', 'pending',
        'task_id', p_task_id,
        'wp_awarded', 0
    );

end;
$$;


