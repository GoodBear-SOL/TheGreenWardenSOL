create or replace function public.get_admin_task_reviews()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_claims jsonb;
begin

    if not public.is_current_user_admin() then

        return jsonb_build_object(
            'ok', false,
            'error', 'ADMIN_REQUIRED',
            'claims', '[]'::jsonb
        );

    end if;


    select coalesce(
        jsonb_agg(
            jsonb_build_object(

                'user_id',
                    tc.user_id,

                'task_id',
                    tc.task_id,

                'task_label',
                    t.label,

                'wp_reward',
                    t.wp_reward,

                'wp_awarded',
                    tc.wp_awarded,

                'proof_url',
                    tc.proof_url,

                'status',
                    tc.status,

                'claimed_at',
                    tc.claimed_at,

                'reviewed_at',
                    tc.reviewed_at,

                'reviewed_by',
                    tc.reviewed_by,

                'username',
                    p.username,

                'google_name',
                    p.google_name,

                'x_username',
                    p.x_username,

                'avatar_url',
                    p.avatar_url

            )
            order by tc.claimed_at asc
        ),
        '[]'::jsonb
    )
    into v_claims

    from public.task_claims tc

    join public.tasks t
      on t.id = tc.task_id

    left join public.profiles p
      on p.id = tc.user_id

    where tc.status = 'pending';


    return jsonb_build_object(
        'ok', true,
        'claims', v_claims
    );

end;
$$;


/* ================================================================
   SECTION 15
   APPROVE TASK CLAIM
   ================================================================ */

create or replace function public.approve_task_claim(
    p_user_id uuid,
    p_task_id text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare

    v_claim public.task_claims;

    v_task public.tasks;

    v_admin uuid := auth.uid();

begin

    if not public.is_current_user_admin() then

        return jsonb_build_object(
            'ok', false,
            'error', 'ADMIN_REQUIRED'
        );

    end if;


    select *
    into v_claim
    from public.task_claims
    where user_id = p_user_id
      and task_id = p_task_id
    for update;


    if not found then

        return jsonb_build_object(
            'ok', false,
            'error', 'CLAIM_NOT_FOUND'
        );

    end if;


    if v_claim.status = 'approved' then

        return jsonb_build_object(
            'ok', false,
            'error', 'ALREADY_APPROVED'
        );

    end if;


    select *
    into v_task
    from public.tasks
    where id = p_task_id;


    if not found then

        return jsonb_build_object(
            'ok', false,
            'error', 'TASK_NOT_FOUND'
        );

    end if;


    update public.task_claims
    set
        status = 'approved',
        wp_awarded = v_task.wp_reward,
        reviewed_at = now(),
        reviewed_by = v_admin
    where user_id = p_user_id
      and task_id = p_task_id;


    update public.profiles
    set
        wp = coalesce(wp, 0) + v_task.wp_reward
    where id = p_user_id;


    return jsonb_build_object(
        'ok', true,
        'status', 'approved',
        'wp_awarded', v_task.wp_reward
    );

end;
$$;


/* ================================================================
