create or replace function public.manila_today()
returns date
language sql
stable
as $$
    select (now() at time zone 'Asia/Manila')::date;
$$;


create or replace function public.manila_seconds_to_reset()
returns integer
language plpgsql
stable
as $$
declare
    v_now timestamp;
    v_next timestamp;
begin

    v_now :=
        now() at time zone 'Asia/Manila';

    v_next :=
        date_trunc('day', v_now) + interval '1 day';

    return greatest(
        0,
        extract(
            epoch from (v_next - v_now)
        )::integer
    );
end;
$$;


/* ================================================================
   SECTION 6
   REWARD LADDER
   ================================================================ */

create or replace function public.wp_for_day(
    p_day integer
)
returns integer
language sql
immutable
as $$
    select case
        when p_day = 1 then 5
        when p_day = 2 then 10
        when p_day = 3 then 15
        when p_day = 4 then 20
        when p_day = 5 then 25
        when p_day = 6 then 30
        when p_day = 7 then 50
        else 5
    end;
$$;


/* ================================================================
   SECTION 7
   EFFECTIVE STREAK
   ================================================================ */

create or replace function public.effective_streak(
    p_last date,
    p_streak integer
)
returns integer
language plpgsql
immutable
as $$
begin

    if p_last is null then
        return 0;
    end if;

    if p_last = current_date then
        return greatest(0, p_streak);
    end if;

    if p_last = current_date - 1 then
        return greatest(0, p_streak);
    end if;

    return 0;

end;
$$;


/* ================================================================
   SECTION 8
   GET MY STATUS
   ================================================================

   Returns the exact fields consumed by dashboard.html:

       id
       username
       google_name
       avatar_url
       x_username
       wallet_address
       wp
       streak
       best_streak
       last_checkin
       claimed_today
       day
       day_in_cycle
       wp_awarded
       seconds_to_reset
       rank
   ================================================================ */

create or replace function public.get_my_status()
returns json
language plpgsql
security definer
set search_path = public
as $$
declare

    v_user uuid := auth.uid();

    p public.profiles;

    v_today date;

    v_claimed boolean := false;

    v_day integer := 1;

    v_wp integer := 5;

    v_rank bigint := 0;

    v_streak integer := 0;

begin

    if v_user is null then
        raise exception 'NOT_AUTHENTICATED';
    end if;


    p := public.ensure_profile();

    v_today := public.manila_today();


    select exists (
        select 1
        from public.checkins c
        where c.user_id = v_user
          and c.day = v_today
    )
    into v_claimed;


    v_streak := public.effective_streak(
        p.last_checkin,
        p.streak
    );


    if v_claimed then

        select
            c.day_in_cycle,
            c.wp_awarded
        into
            v_day,
            v_wp
        from public.checkins c
        where c.user_id = v_user
          and c.day = v_today
        order by c.created_at desc
        limit 1;

    else

        v_day :=
            case
                when v_streak > 0
                    then ((v_streak % 7) + 1)
                else 1
            end;

        v_wp :=
            public.wp_for_day(v_day);

    end if;


    select count(*) + 1
    into v_rank
    from public.profiles p2
    where p2.wp > p.wp;


    return json_build_object(

        'id',
            p.id,

        'username',
            p.username,

        'google_name',
            p.google_name,

        'avatar_url',
            p.avatar_url,

        'x_username',
            p.x_username,

        'wallet_address',
            p.wallet_address,

        'wp',
            coalesce(p.wp, 0),

        'streak',
            v_streak,

        'best_streak',
            coalesce(p.best_streak, 0),

        'last_checkin',
            p.last_checkin,

        'claimed_today',
            v_claimed,

        'day',
            v_day,

        'day_in_cycle',
            v_day,

        'wp_awarded',
            v_wp,

        'seconds_to_reset',
            public.manila_seconds_to_reset(),

        'rank',
            v_rank,

        'is_admin',
            coalesce(p.is_admin, false)

    );

end;
$$;


/* ================================================================
   SECTION 9
   CLAIM CHECK-IN
   ================================================================ */

create or replace function public.claim_checkin()
returns json
language plpgsql
security definer
set search_path = public
as $$
declare

    v_user uuid := auth.uid();

    v_today date;

    v_profile public.profiles;

    v_day integer;

    v_reward integer;

    v_new_streak integer;

    v_best integer;

begin

    if v_user is null then
        raise exception 'NOT_AUTHENTICATED';
    end if;


    v_profile := public.ensure_profile();

    v_today := public.manila_today();


    /* ------------------------------------------------------------
       Prevent duplicate daily claim
       ------------------------------------------------------------ */

    if exists (
        select 1
        from public.checkins
        where user_id = v_user
          and day = v_today
    ) then

        return json_build_object(
            'ok', false,
            'wp_awarded', 0,
            'day', (
                select day_in_cycle
                from public.checkins
                where user_id = v_user
                  and day = v_today
                limit 1
            ),
            'streak', v_profile.streak
        );

    end if;


    /* ------------------------------------------------------------
       Determine streak
       ------------------------------------------------------------ */

    if v_profile.last_checkin = v_today - 1 then

        v_new_streak :=
            greatest(0, v_profile.streak) + 1;

    else

        v_new_streak := 1;

    end if;


    v_day :=
        ((v_new_streak - 1) % 7) + 1;


    v_reward :=
        public.wp_for_day(v_day);


    v_best :=
        greatest(
            coalesce(v_profile.best_streak, 0),
            v_new_streak
        );


    /* ------------------------------------------------------------
       Record check-in
       ------------------------------------------------------------ */

    insert into public.checkins (
        user_id,
        day,
        day_in_cycle,
        wp_awarded
    )
    values (
        v_user,
        v_today,
        v_day,
        v_reward
    );


    /* ------------------------------------------------------------
       Award WP
       ------------------------------------------------------------ */

    update public.profiles
    set
        wp = coalesce(wp, 0) + v_reward,
        streak = v_new_streak,
        best_streak = v_best,
        last_checkin = v_today
    where id = v_user;


    /* ------------------------------------------------------------
       Referral qualification is checked separately by
       qualify_referral() as dashboard.html expects.
       ------------------------------------------------------------ */


    return json_build_object(

        'ok',
            true,

        'wp_awarded',
            v_reward,

        'day',
            v_day,

        'streak',
            v_new_streak

    );

end;
$$;


