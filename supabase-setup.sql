/* ================================================================
   SECTION 21
   UPDATE PROFILE
   ================================================================ */

create or replace function public.update_profile(
    p_username text,
    p_x_username text,
    p_wallet_address text
)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare

    v_user uuid := auth.uid();

    v_profile public.profiles;

    v_username text :=
        nullif(trim(coalesce(p_username, '')), '');

    v_x text :=
        nullif(
            trim(
                regexp_replace(
                    coalesce(p_x_username, ''),
                    '^@+',
                    ''
                )
            ),
            ''
        );

    v_wallet text :=
        nullif(trim(coalesce(p_wallet_address, '')), '');

    v_x_bonus integer := 0;

    v_wallet_bonus integer := 0;

begin

    if v_user is null then

        return json_build_object(
            'ok', false,
            'error', 'NOT_AUTHENTICATED'
        );

    end if;


    perform public.ensure_profile();


    /* ------------------------------------------------------------
       Username validation
       ------------------------------------------------------------ */

    if v_username is not null
       and v_username !~ '^[A-Za-z0-9_]{3,20}$' then

        return json_build_object(
            'ok', false,
            'error', 'INVALID_USERNAME'
        );

    end if;


    /* ------------------------------------------------------------
       X validation
       ------------------------------------------------------------ */

    if v_x is not null
       and v_x !~ '^[A-Za-z0-9_]{1,15}$' then

        return json_build_object(
            'ok', false,
            'error', 'INVALID_X'
        );

    end if;


    /* ------------------------------------------------------------
       Wallet validation
       ------------------------------------------------------------ */

    if v_wallet is not null
       and not public.is_valid_solana_address(v_wallet) then

        return json_build_object(
            'ok', false,
            'error', 'INVALID_WALLET'
        );

    end if;


    /* ------------------------------------------------------------
       Username uniqueness
       ------------------------------------------------------------ */

    if v_username is not null
       and exists (
            select 1
            from public.profiles p
            where lower(p.username) = lower(v_username)
              and p.id <> v_user
       ) then

        return json_build_object(
            'ok', false,
            'error', 'USERNAME_TAKEN'
        );

    end if;


    select *
    into v_profile
    from public.profiles
    where id = v_user
    for update;


    /* ------------------------------------------------------------
       First-time X bonus = +5 WP
       ------------------------------------------------------------ */

    if v_x is not null
       and coalesce(v_profile.x_username, '') = ''
       and not v_profile.x_bonus_claimed then

        v_x_bonus := 5;

    end if;


    /* ------------------------------------------------------------
       First-time wallet bonus = +5 WP
       ------------------------------------------------------------ */

    if v_wallet is not null
       and coalesce(v_profile.wallet_address, '') = ''
       and not v_profile.wallet_bonus_claimed then

        v_wallet_bonus := 5;

    end if;


    update public.profiles
    set

        username = v_username,

        x_username = v_x,

        wallet_address = v_wallet,

        x_bonus_claimed =
            case
                when v_x_bonus > 0 then true
                else x_bonus_claimed
            end,

        wallet_bonus_claimed =
            case
                when v_wallet_bonus > 0 then true
                else wallet_bonus_claimed
            end,

        wp =
            coalesce(wp, 0)
            + v_x_bonus
            + v_wallet_bonus

    where id = v_user

    returning *
    into v_profile;


    return json_build_object(

        'ok', true,

        'username',
            v_profile.username,

        'x_username',
            v_profile.x_username,

        'wallet_address',
            v_profile.wallet_address,

        'x_bonus',
            v_x_bonus,

        'wallet_bonus',
            v_wallet_bonus,

        'total_bonus',
            v_x_bonus + v_wallet_bonus

    );

end;
$$;


/* ================================================================
   SECTION 22
   REFERRAL CODE GENERATOR
   ================================================================ */

create or replace function public.generate_referral_code()
returns text
language plpgsql
security definer
set search_path = public
as $$
declare

    v_user uuid := auth.uid();

    v_existing text;

    v_code text;

begin

    if v_user is null then
        raise exception 'AUTH_REQUIRED';
    end if;


    select referral_code
    into v_existing
    from public.referral_codes
    where user_id = v_user
    limit 1;


    if v_existing is not null then
        return v_existing;
    end if;


    v_code :=
        'GW' ||
        upper(
            substr(
                replace(v_user::text, '-', ''),
                1,
                8
            )
        );


    begin

        insert into public.referral_codes (
            user_id,
            referral_code
        )
        values (
            v_user,
            v_code
        );

    exception
        when unique_violation then

            v_code :=
                'GW' ||
                upper(
                    substr(
                        replace(v_user::text, '-', ''),
                        1,
                        12
                    )
                );

            insert into public.referral_codes (
                user_id,
                referral_code
            )
            values (
                v_user,
                v_code
            );

    end;


    return v_code;

end;
$$;


