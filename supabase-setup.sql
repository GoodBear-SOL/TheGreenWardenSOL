CREATE FUNCTION public.get_task_board()
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_user uuid := auth.uid(); v_tasks jsonb; v_claims jsonb;
BEGIN
  IF v_user IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'error', 'NOT_AUTHENTICATED');
  END IF;
  PERFORM public.ensure_profile();

  SELECT COALESCE(jsonb_agg(jsonb_build_object(
    'id', t.id, 'label', t.label, 'url', t.url, 'wp_reward', t.wp_reward,
    'needs_proof', t.needs_proof, 'active', t.active, 'sort_order', t.sort_order
  ) ORDER BY t.sort_order, t.created_at), '[]'::jsonb)
  INTO v_tasks FROM public.tasks t WHERE t.active = true;

  SELECT COALESCE(jsonb_agg(jsonb_build_object(
    'user_id', tc.user_id, 'task_id', tc.task_id, 'proof_url', tc.proof_url,
    'wp_awarded', tc.wp_awarded, 'status', COALESCE(tc.status, 'approved'),
    'claimed_at', tc.claimed_at, 'reviewed_at', tc.reviewed_at, 'reviewed_by', tc.reviewed_by
  ) ORDER BY tc.claimed_at DESC), '[]'::jsonb)
  INTO v_claims FROM public.task_claims tc WHERE tc.user_id = v_user;

  RETURN jsonb_build_object('ok', true, 'tasks', v_tasks, 'task_claims', v_claims);
END $$;

CREATE FUNCTION public.submit_task_for_review(p_task_id text, p_proof_url text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_user uuid := auth.uid(); v_task public.tasks; v_existing public.task_claims; v_url text;
BEGIN
  IF v_user IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'error', 'NOT_AUTHENTICATED');
  END IF;
  PERFORM public.ensure_profile();

  v_url := btrim(COALESCE(p_proof_url, ''));
  IF v_url = '' THEN
    RETURN jsonb_build_object('ok', false, 'error', 'PROOF_REQUIRED');
  END IF;
  IF v_url !~* '^https?://(www\.)?(x\.com|twitter\.com)/.+' THEN
    RETURN jsonb_build_object('ok', false, 'error', 'INVALID_X_PROOF_URL');
  END IF;

  SELECT * INTO v_task FROM public.tasks WHERE id = p_task_id;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('ok', false, 'error', 'UNKNOWN_TASK');
  END IF;
  IF NOT v_task.active THEN
    RETURN jsonb_build_object('ok', false, 'error', 'TASK_INACTIVE');
  END IF;

  SELECT * INTO v_existing FROM public.task_claims
   WHERE user_id = v_user AND task_id = p_task_id FOR UPDATE;

  IF FOUND THEN
    IF COALESCE(v_existing.status, 'approved') = 'approved' THEN
      RETURN jsonb_build_object('ok', false, 'error', 'ALREADY_APPROVED');
    END IF;
    IF v_existing.status = 'pending' THEN
      RETURN jsonb_build_object('ok', false, 'error', 'ALREADY_PENDING');
    END IF;
    UPDATE public.task_claims
       SET proof_url = v_url, status = 'pending', claimed_at = now(),
           reviewed_at = NULL, reviewed_by = NULL, wp_awarded = 0
     WHERE user_id = v_user AND task_id = p_task_id;
  ELSE
    INSERT INTO public.task_claims (user_id, task_id, wp_awarded, proof_url, claimed_at, status)
    VALUES (v_user, p_task_id, 0, v_url, now(), 'pending');
  END IF;

  RETURN jsonb_build_object('ok', true, 'status', 'pending', 'task_id', p_task_id);
EXCEPTION WHEN unique_violation THEN
  RETURN jsonb_build_object('ok', false, 'error', 'ALREADY_PENDING');
END $$;

