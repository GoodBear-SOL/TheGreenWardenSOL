/* ============================================================
   THE GREEN WARDEN — SUPABASE MASTER SETUP / REPAIR SCRIPT (v2)
   Safe to re-run. Matches dashboard.html RPC shapes.

   Rules:
   - Attaching a referral -> REFERRER gets +200 WP immediately, once.
   - Referred user reaches a 7-day streak -> REFERRER gets an additional +300 WP, once.
   - Maximum referral reward = +500 WP per referral.
   - 7-day qualification runs server-side inside claim_checkin (and via qualify_referral).
