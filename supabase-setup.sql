CREATE FUNCTION public.get_admin_task_reviews()
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_claims jsonb;
BEGIN
  IF NOT public.is_current_user_admin() THEN
    RETURN jsonb_build_object('ok', false, 'error', 'ADMIN_REQUIRED');
  END IF;

  SELECT COALESCE(jsonb_agg(jsonb_build_object(
    'user_id', tc.user_id, 'task_id', tc.task_id, 'proof_url', tc.proof_url,
    'wp_awarded', tc.wp_awarded, 'status', tc.status, 'claimed_at', tc.claimed_at,
    'reviewed_at', tc.reviewed_at, 'reviewed_by', tc.reviewed_by,
    'username', p.username, 'google_name', p.google_name,
    'x_username', p.x_username, 'avatar_url', p.avatar_url,
    'task_label', t.label, 'task_url', t.url,
    'task_reward', t.wp_reward, 'wp_reward', t.wp_reward
  ) ORDER BY tc.claimed_at ASC), '[]'::jsonb)
  INTO v_claims
  FROM public.task_claims tc
  JOIN public.profiles p ON p.id = tc.user_id
  JOIN public.tasks t ON t.id = tc.task_id
  WHERE tc.status = 'pending';

  RETURN jsonb_build_object('ok', true, 'claims', v_claims);
END $$;

CREATE FUNCTION public.approve_task_claim(p_user_id uuid, p_task_id text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_claim public.task_claims; v_task public.tasks;
BEGIN
  IF NOT public.is_current_user_admin() THEN
    RETURN jsonb_build_object('ok', false, 'error', 'ADMIN_REQUIRED');
  END IF;

  SELECT * INTO v_claim FROM public.task_claims
   WHERE user_id = p_user_id AND task_id = p_task_id FOR UPDATE;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('ok', false, 'error', 'CLAIM_NOT_FOUND');
  END IF;
  IF COALESCE(v_claim.status, 'approved') = 'approved' THEN
    RETURN jsonb_build_object('ok', false, 'error', 'ALREADY_APPROVED');
  END IF;

  SELECT * INTO v_task FROM public.tasks WHERE id = p_task_id;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('ok', false, 'error', 'UNKNOWN_TASK');
  END IF;

  UPDATE public.task_claims
     SET status = 'approved', wp_awarded = v_task.wp_reward,
         reviewed_at = now(), reviewed_by = auth.uid()
   WHERE user_id = p_user_id AND task_id = p_task_id;

  UPDATE public.profiles SET wp = COALESCE(wp,0) + v_task.wp_reward WHERE id = p_user_id;

  RETURN jsonb_build_object('ok', true, 'wp_awarded', v_task.wp_reward,
                            'task_id', p_task_id, 'user_id', p_user_id);
END $$;

CREATE FUNCTION public.reject_task_claim(p_user_id uuid, p_task_id text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_claim public.task_claims;
BEGIN
  IF NOT public.is_current_user_admin() THEN
    RETURN jsonb_build_object('ok', false, 'error', 'ADMIN_REQUIRED');
  END IF;

  SELECT * INTO v_claim FROM public.task_claims
   WHERE user_id = p_user_id AND task_id = p_task_id FOR UPDATE;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('ok', false, 'error', 'CLAIM_NOT_FOUND');
  END IF;
  IF COALESCE(v_claim.status, 'approved') = 'approved' THEN
    RETURN jsonb_build_object('ok', false, 'error', 'ALREADY_APPROVED');
  END IF;

  UPDATE public.task_claims
