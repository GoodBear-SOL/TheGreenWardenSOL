/* ------------------------------------------------
   Helper to safely create policies.
   ------------------------------------------------ */

do $$
begin

    /* profiles: users can read their own profile */
    if not exists (
        select 1
        from pg_policies
        where schemaname = 'public'
          and tablename = 'profiles'
          and policyname = 'profiles_select_own'
    ) then

        create policy profiles_select_own
        on public.profiles
        for select
        to authenticated
        using (id = auth.uid());

    end if;


    /* tasks: authenticated users can see active tasks */
    if not exists (
        select 1
        from pg_policies
        where schemaname = 'public'
          and tablename = 'tasks'
          and policyname = 'tasks_select_active'
    ) then

        create policy tasks_select_active
        on public.tasks
        for select
        to authenticated
        using (active = true);

    end if;


    /* task claims: users can see their own claims */
    if not exists (
        select 1
        from pg_policies
        where schemaname = 'public'
          and tablename = 'task_claims'
          and policyname = 'task_claims_select_own'
    ) then

        create policy task_claims_select_own
        on public.task_claims
        for select
        to authenticated
        using (user_id = auth.uid());

    end if;


    /* referral code: own code */
    if not exists (
        select 1
        from pg_policies
        where schemaname = 'public'
          and tablename = 'referral_codes'
          and policyname = 'referral_codes_select_own'
    ) then

        create policy referral_codes_select_own
        on public.referral_codes
        for select
        to authenticated
        using (user_id = auth.uid());

    end if;


    /* referrals: users can see referrals where they are involved */
    if not exists (
        select 1
        from pg_policies
        where schemaname = 'public'
          and tablename = 'referrals'
          and policyname = 'referrals_select_involved'
    ) then

        create policy referrals_select_involved
        on public.referrals
        for select
        to authenticated
        using (
            referrer_id = auth.uid()
            or referred_id = auth.uid()
        );

    end if;


    /* referral rewards: referrer can see own rewards */
    if not exists (
        select 1
        from pg_policies
        where schemaname = 'public'
          and tablename = 'referral_rewards'
          and policyname = 'referral_rewards_select_own'
    ) then

        create policy referral_rewards_select_own
        on public.referral_rewards
        for select
        to authenticated
        using (referrer_id = auth.uid());

    end if;


    /* check-ins: user can see own check-ins */
    if not exists (
        select 1
        from pg_policies
        where schemaname = 'public'
          and tablename = 'checkins'
          and policyname = 'checkins_select_own'
    ) then

        create policy checkins_select_own
        on public.checkins
        for select
        to authenticated
        using (user_id = auth.uid());

    end if;

end;
$$;


